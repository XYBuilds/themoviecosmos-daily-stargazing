"""C2 正文句式红线检测器（ADR-0019 D0/D1）。

能力边界（务必对齐 ADR-0019 D0，不要在本模块内扩权）：
- 本模块只抓**句式类**红线（硬转场 / 说破盖章 / 接受度单独成句），
  用确定性正则，不涉及任何语义判断。语义幻觉（overview 没写的画面 / 写错
  的导演名等）不归本模块，那是 `judge_body_fabrication`（LLM-judge）的职责。
- `scan` 是**检测器**，不是编排器：只返回违规清单，不改写正文、不调用任何
  LLM、不做任何 IO。是否重试、如何拼反馈，全部交给上游的 `run_publish`
  （ADR-0019 D3）。

FP 哲学（复刻 `scripts/compose.py::render_movie_header`）：
- `RULES` 是模块级常量表，声明式组织：新增 / 调整一条红线 = 往表里加一行
  `(rule_id, pattern, description)`，不需要改 `scan` 的遍历逻辑。
- `scan` 本身是纯函数：相同输入永远得到相同输出，不修改传入的 `body`。
"""

from __future__ import annotations

import re
from typing import NamedTuple

__all__ = ["Violation", "RULES", "scan"]


class Violation(NamedTuple):
    """一次红线命中记录（不可变）。

    - `rule_id`：命中的规则标识，供上游按规则聚合 / 拼 repair_context。
    - `snippet`：命中的原文片段（正则整体匹配到的文本），供 12.4 把「原文
      长这样」喂回 LLM 当反馈证据，而不是让 LLM 猜哪句话违规。
    - `description`：该规则抓的意图说明（人话，不是复述正则本身）。
    """

    rule_id: str
    snippet: str
    description: str


# ---------------------------------------------------------------------------
# RULES：句式红线 DSL 表。每项 = (rule_id, 已编译正则, 意图描述)。
#
# 扩展方式：新观察到一种违规句式 → 在此表末尾加一行 (id, pattern, desc)，
# `scan` 不用改。这是 ADR-0019 D1 明确要求的「新增/调整红线 = 加一行」。
# ---------------------------------------------------------------------------

RULES: list[tuple[str, re.Pattern[str], str]] = [
    (
        "hard_transition",
        # 抓「而这(部/恰/正)……电影」这种把新闻硬转到电影的转场骨架。
        # 锚定「而这」+ 部/恰/正其中一字，中间容许一小段修饰语，
        # 但要求在不太远（<=40 字、不跨句号/问号/叹号）的范围内出现「电影」，
        # 避免误伤普通含「而」但与转场无关的句子。
        re.compile(r"而这(?:部|恰|正)[^。！？]{0,40}?电影"),
        "把新闻硬转到电影的套话转场，如「而这部…电影」「而这恰好也是…电影」",
    ),
    (
        "parallel_dianpo",
        # 抓「无论是……都……」骨架——真实样本里「还是」并非必现
        # （如「无论是哪一种画面，核心都悬在同一个问题上」只有「都」没有
        # 「还是」），但「无论是」之后接一个「都」收束，本身就是并列点破
        # 的核心标记，故以此为锚，不强制要求「还是」同时出现。
        re.compile(r"无论是.{0,150}?都"),
        "「无论是…（还是…）都…」式并列点破，替读者把几件事拎出来对照",
    ),
    (
        "verdict_stamp",
        # 抓「同一种/同一个」这类强盖章词——这是最难绕开换词的信号，
        # 不要求前面必须出现「都/背后是」（真实样本里也有单独出现的情况，
        # 如「本质上源自同一种对失控力量的恐惧」），故意收窄到这两个强词，
        # 不去抓较弱的「两者都在问」之类（那类靠人工/后续加行扩展）。
        re.compile(r"同一(?:种|个)"),
        "「都/背后是…同一种/同一个…」式论点盖章，替读者总结出「本质是同一种 X」",
    ),
    (
        "acceptance_standalone",
        # 抓「以『这部电影/这部影片/电影』开头 + 含评价类关键词 + 句号收尾」
        # 的独立整句。用零宽断言锚定句首（字符串起始或紧跟句末标点/换行），
        # 借此把「揉进从句中段」的写法排除在外——那类反例天然不会落在句首。
        re.compile(
            r"(?:^|(?<=[。！？\n]))(?:这部(?:电影|影片)|电影)"
            r"[^。！？]{0,80}?(?:评价|口碑|看过的人|观众)[^。！？]{0,80}?。"
        ),
        "把接受度（看过多少人、口碑形态）单独写成一整句，而非揉进从句",
    ),
]


def scan(body: str) -> list[Violation]:
    """对正文 `body` 做一次确定性句式红线扫描，返回命中列表。

    纯函数契约：
    - 只读 `body`，不修改、不返回改写后的文本；
    - 不发起任何网络 / LLM 调用，不读写文件；
    - 相同的 `body` 输入永远得到内容相同的 `Violation` 列表。

    行为说明：按 `RULES` 表顺序遍历，每条规则用 `finditer` 找出**全部**
    命中位置——同一条规则在同一段正文里命中多处，会各自记一条
    `Violation`（不做去重）。这样上游（ADR-0019 D3 的重试编排）能看到
    违规的实际出现次数与每一处原文片段，而不是被静默合并成一条。
    """

    violations: list[Violation] = []
    for rule_id, pattern, description in RULES:
        for match in pattern.finditer(body):
            violations.append(
                Violation(rule_id=rule_id, snippet=match.group(0), description=description)
            )
    return violations